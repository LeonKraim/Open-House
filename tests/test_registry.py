ROOT = paths.ROOT
COMMITTED = ROOT / layout.DIRECTORY
SCENARIOS = ROOT / "scenarios"

#: A commit that is the right shape for a pointer's `commit` field.
COMMIT = "a1b2c3d4" * 5


@pytest.fixture(scope="module")
def vocabulary() -> Vocabulary:
    """The committed catalog, loaded once for the module."""
    return Vocabulary.load(ROOT)


def _registry(tmp_path: Path) -> Path:
    """A writable registry: the committed policy files, and no pointers yet.

    The schema and the tier list are the committed ones, copied rather than
    restated, because the point of the temporary tree is to exercise publishing
    against the real rules -- a hand-written stand-in for the tiers would let a
    change to `registry/tiers.yaml` pass this suite untouched.
    """
    root = tmp_path / "registry"
    (root / layout.POINTERS_DIRECTORY).mkdir(parents=True)
    for name in (layout.POINTER_SCHEMA_FILENAME, layout.TIERS_FILENAME):
        shutil.copyfile(COMMITTED / name, root / name)
    (root / layout.REVOCATIONS_FILENAME).write_text(
        "revocations: []\n", encoding="utf-8"
    )
    return root


def _install_root(tmp_path: Path) -> Path:
    """A repository to install into: the committed tree's data, and no packs yet.

    A pack installs against the repository root the engine is opened at, so a
    pack a third party publishes has to be installed into a repository that
    *holds* it. Copying the catalog, the schemas and the packs is what makes the
    temporary root a real one: the engine reads the catalog for its vocabulary
    and the schemas for its manifest artefacts, and a root missing either would
    fail for a reason that is not the registry's.
    """
    root = tmp_path / "install"
    for name in ("catalog", "schemas", "packs"):
        shutil.copytree(ROOT / name, root / name)
    return root


def _staged(
    install_root: Path,
    directory: str,
    *,
    name: str,
    version: str,
    services: tuple[str, ...],
) -> Path:
    """Write a pack under `install_root` and export it to the repo-relative form.

    The pack is built with an absolute `provides` path -- the form a pack
    developed outside its repository carries -- and then exported, which is the
    publishing button's first act. What lands on disk is the manifest a publisher
    commits: paths that resolve against the repository root, not against the
    machine the pack was developed on.
    """
    manifest = pack(
        install_root / "packs" / "community",
        directory,
        version=version,
        services=services,
        edits=(("name: ", f"name: {name}"),),
    )
    template = export_template(manifest, root=install_root)
    manifest.write_text(
        yaml.safe_dump(template, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    return manifest


def _publish(
    registry: Path,
    install_root: Path,
    directory: str,
    *,
    name: str,
    version: str,
    services: tuple[str, ...],
) -> Pointer:
    """Stage and publish one version, returning the pointer that pins it."""
    manifest = _staged(
        install_root, directory, name=name, version=version, services=services
    )
    publication = publish(
        registry,
        manifest,
        repo=install_root.as_posix(),
        commit=COMMIT,
        tier="community",
    )
    return publication.pointer


def _entry_of(registry: Path, name: str, version: str) -> Pointer:
    """The pointer the committed index carries for `name` at `version`."""
    entry = load_index(registry).find(name, version)
    assert entry is not None, f"{name} {version} is not in the index"
    return entry.pointer


# -- the four tiers ---------------------------------------------------------


def test_the_four_tiers_are_exactly_the_ones_the_policy_closes() -> None:
    """A tree that dropped or added a tier would make a pointer unjudgeable."""
    tiers = load_tiers(COMMITTED)
    assert tuple(tiers) == TIER_NAMES


def test_only_the_local_tier_stays_out_of_the_index() -> None:
    """A sideloaded pack is not published, and every other tier is."""
    tiers = load_tiers(COMMITTED)
    published = {name for name, tier in tiers.items() if tier.publishes}
    assert published == {"official", "verified", "community"}
    assert tiers["local"].install_flow == "config"
    assert tiers["local"].banner is not None


def test_an_unreviewed_tier_may_not_permit_a_dangerous_permission() -> None:
    """A community pack is accepted without review, so it carries no danger."""
    tiers = load_tiers(COMMITTED)
    assert not tiers["community"].permits_flagged
    assert tiers["official"].permits_flagged
    assert tiers["verified"].permits_flagged


def test_a_tier_list_missing_one_tier_is_refused(tmp_path: Path) -> None:
    """Dropping `local` would leave every `local` pointer unjudgeable."""
    registry = _registry(tmp_path)
    document = yaml.safe_load(
        (registry / layout.TIERS_FILENAME).read_text(encoding="utf-8")
    )
    document["tiers"] = [row for row in document["tiers"] if row["name"] != "local"]
    (registry / layout.TIERS_FILENAME).write_text(
        yaml.safe_dump(document, sort_keys=False), encoding="utf-8"
    )
    with pytest.raises(TierError):
        load_tiers(registry)


