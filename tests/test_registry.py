"""The registry and the community store, end to end.

The registry's claim is a lifecycle rather than a shape: a third party exports a
pack, publishes it under a tier, and a household can then browse the index,
install the pack by digest, and run it. This module drives that whole path -- on
a temporary registry (a fresh copy of the committed schema, tiers and empty
revocation list) and against a temporary installation root (a copy of the
committed catalog, schemas and packs) -- so the scenario the phase exists for is
exercised rather than described:

    export -> publish -> generate -> check -> browse -> install -> run

The packs are generated by `packfactory` rather than committed, because a pack a
third party publishes is exactly one the repository does not contain, and a
committed fixture would be a pack the store could have reached a second way.
Where a check's *failure* is the point -- a revoked pack, a widened grant, a
typosquat -- the violating input is built here for the same reason the other
suites build theirs.

Every check names the implementation that would falsify it. The recurring claim
is that the publishing side and the consuming side read one pointer tree and one
digest, and that a published manifest's `provides` paths are the repo-relative
form the sandbox installs -- so a change that made the two disagree would turn
one of these red.
"""

